import { existsSync, mkdirSync, readdirSync, cpSync, rmSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

let resolverRegistered = false;

/**
 * Resolves the root directory of the installed/running buntic package.
 */
export function getPackageRoot(): string {
  let current = dirname(fileURLToPath(import.meta.url));
  while (true) {
    const pkgPath = join(current, "package.json");
    if (existsSync(pkgPath)) {
      try {
        const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
        if (pkg?.name === "buntic") {
          return current;
        }
      } catch {
        // continue walking up
      }
    }
    const parent = dirname(current);
    if (parent === current) {
      break;
    }
    current = parent;
  }
  return resolve(dirname(fileURLToPath(import.meta.url)), "..");
}

/**
 * Returns the runtime entry point for the currently running buntic package.
 */
export function getSelfEntryPath(): string {
  const pkgRoot = getPackageRoot();
  const currentFile = fileURLToPath(import.meta.url);
  const distEntry = join(pkgRoot, "dist", "index.js");
  const srcEntry = join(pkgRoot, "src", "index.ts");

  if (currentFile.startsWith(join(pkgRoot, "dist")) && existsSync(distEntry)) {
    return distEntry;
  }
  if (existsSync(srcEntry)) {
    return srcEntry;
  }
  return distEntry;
}

/**
 * Checks whether a project directory (or any ancestor) has a local node_modules/buntic installation.
 */
export function hasLocalBunticPackage(startDir: string): boolean {
  let current = resolve(startDir);
  while (true) {
    if (existsSync(join(current, "node_modules", "buntic", "package.json"))) {
      return true;
    }
    const parent = dirname(current);
    if (parent === current) {
      return false;
    }
    current = parent;
  }
}

/**
 * Registers a runtime Bun.plugin so projects without package.json / node_modules
 * can import from "buntic" (e.g. buntic.config.ts, storage/*.ts) when executed
 * via a globally installed buntic CLI.
 */
export function registerBunticModuleResolver(projectDir?: string): void {
  if (resolverRegistered) return;
  if (projectDir && hasLocalBunticPackage(projectDir)) return;
  resolverRegistered = true;

  const selfEntry = getSelfEntryPath();

  Bun.plugin({
    name: "buntic-global-self-resolver",
    setup(build) {
      build.module("buntic", async () => {
        const mod = await import(selfEntry);
        return {
          exports: { ...mod },
          loader: "object",
        };
      });
    },
  });
}

function copyDeclarationFiles(srcDir: string, destDir: string): number {
  let count = 0;
  mkdirSync(destDir, { recursive: true });
  for (const entry of readdirSync(srcDir, { withFileTypes: true })) {
    const srcPath = join(srcDir, entry.name);
    const destPath = join(destDir, entry.name);
    if (entry.isDirectory()) {
      count += copyDeclarationFiles(srcPath, destPath);
    } else if (entry.isFile() && entry.name.endsWith(".d.ts")) {
      cpSync(srcPath, destPath);
      count++;
    }
  }
  return count;
}

/**
 * Copies Buntic's .d.ts declarations into .buntic/types/ so TypeScript / VS Code
 * provides full autocomplete and type checking in zero-package.json projects via tsconfig paths.
 */
export function syncProjectTypes(projectRoot: string): boolean {
  const absRoot = resolve(projectRoot);
  if (hasLocalBunticPackage(absRoot)) {
    return false;
  }

  const pkgRoot = getPackageRoot();
  let version = "0.0.0";
  try {
    const pkg = JSON.parse(readFileSync(join(pkgRoot, "package.json"), "utf8"));
    if (pkg?.version) version = pkg.version;
  } catch {
    // ignore
  }

  const bunticDir = join(absRoot, ".buntic");
  const typesDir = join(bunticDir, "types");
  const typesEntry = join(typesDir, "index.d.ts");
  const versionMarkerPath = join(bunticDir, ".types-version");
  const distDir = join(pkgRoot, "dist");
  const hasBuiltTypes = existsSync(join(distDir, "index.d.ts"));
  const expectedMarker = `${version}:${hasBuiltTypes ? "dist" : "src"}`;

  if (
    existsSync(typesEntry) &&
    existsSync(versionMarkerPath) &&
    readFileSync(versionMarkerPath, "utf8").trim() === expectedMarker
  ) {
    return false;
  }

  mkdirSync(bunticDir, { recursive: true });
  if (existsSync(typesDir)) {
    rmSync(typesDir, { recursive: true, force: true });
  }
  mkdirSync(typesDir, { recursive: true });

  if (hasBuiltTypes) {
    copyDeclarationFiles(distDir, typesDir);
  } else {
    // Fallback when running directly from source before dist/ types are built
    const srcIndex = join(pkgRoot, "src", "index.ts").replace(/\\/g, "/");
    writeFileSync(
      typesEntry,
      `// Auto-generated by Buntic (source dev fallback).\nexport * from "${srcIndex}";\n`,
      "utf8"
    );
  }

  writeFileSync(versionMarkerPath, `${expectedMarker}\n`, "utf8");
  return true;
}
